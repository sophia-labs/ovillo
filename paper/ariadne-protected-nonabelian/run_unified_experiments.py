def jsonable(value: Any) -> Any:
    if is_dataclass(value):
        if hasattr(value, "to_json_dict"):
            return jsonable(value.to_json_dict())
        return jsonable(asdict(value))
    if isinstance(value, dict):
        return {str(key): jsonable(item) for key, item in value.items()}
    if isinstance(value, (tuple, list)):
        return [jsonable(item) for item in value]
    if isinstance(value, np.ndarray):
        if np.iscomplexobj(value):
            return complex_matrix_json(value)
        return value.tolist()
    if isinstance(value, np.generic):
        return value.item()
    if isinstance(value, Enum):
        return value.value
    if isinstance(value, complex):
        return [float(value.real), float(value.imag)]
    if isinstance(value, Path):
        return str(value)
    return value


def canonical_json_bytes(value: Any) -> bytes:
    return (
        json.dumps(jsonable(value), sort_keys=True, separators=(",", ":"), allow_nan=False)
        + "\n"
    ).encode("utf-8")


def write_json(path: Path, value: Any) -> None:
    path.write_bytes(canonical_json_bytes(value))


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def value_sha256(value: Any) -> str:
    return hashlib.sha256(canonical_json_bytes(value)).hexdigest()




def source_tree_sha256(root: Path) -> str:
    """Digest the executable reference source without generated bytecode."""
    digest = hashlib.sha256()
    paths = [root / "run_unified_experiments.py"]
    paths.extend(sorted((root / "unified_reference").glob("*.py")))
    paths.extend(sorted((root / "unified_reference" / "tests").glob("*.py")))
    for path in paths:
        relative = path.relative_to(root).as_posix()
        digest.update(relative.encode("utf-8") + b"\0")
        digest.update(path.read_bytes())
        digest.update(b"\0")
    return digest.hexdigest()

def array_bundle_sha256(**arrays: np.ndarray) -> str:
    """Stable digest over named numeric arrays, including shapes and dtypes."""
    digest = hashlib.sha256()
    for name, array in sorted(arrays.items()):
        value = np.asarray(array)
        if np.iscomplexobj(value):
            stable = np.ascontiguousarray(value, dtype="<c16")
        else:
            stable = np.ascontiguousarray(value, dtype="<f8")
        digest.update(name.encode("utf-8") + b"\0")
        digest.update(str(stable.shape).encode("ascii") + b"\0")
        digest.update(stable.dtype.str.encode("ascii") + b"\0")
        digest.update(stable.tobytes(order="C"))
    return digest.hexdigest()


