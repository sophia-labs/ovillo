#!/usr/bin/env python
"""Threader V0 render bank — the training corpus as a ledger of receipts.

The dataset design from the Threader proposal, made concrete: every
example is a `renderWeaveProbe` request (θ = patch, γ = notes/slot/
gliss/trajectory/gesture) plus the engine commit — a pure function, so
the canonical artifact is the MANIFEST (one JSON line per render:
request + receipt), and audio is a regenerable cache. Labels are the
requests themselves; the service's determinism is the provenance.

Strata:
  core      Sobol sweep over the declared safe joint region
            (PARAMETERS.md §8, projected: orbit_depth*couple <= 0.24,
            curvature*couple <= 0.22) extended with the PW10 palette
            (bodyp/bow/bow_speed/breath) — the prior's support.
  contrast  controlled pairs sharing all-but-one factor: body swap,
            chirality mirror, trajectory order reversal (AB vs BA
            blocks), guitar-limit vs weave-mid — the mathematicians'
            controlled-contrast cells, grouped by `group` id.
  witness   Path Witness stimuli through the Phase 2 gesture seam:
            per group one patch+chord rendered with {null word,
            compiled 12-gate closed word, its 24-gate inverse} —
            exact same-endpoint pairs for Experiment 2, generated by
            the machinery the paper specifies rather than approximated.

Gesture-conditioned (Aigua-contour) data is deliberately absent from
V0: within-note pitch automation (target_pitch_ratio ControlTarget) is
not yet in the engine. Recorded here so it is not mistaken for scope
creep later.

Incremental + resumable: manifest lines append per render and existing
ids are skipped, so an interrupted run resumes and a bounded overnight
run delivers whatever it reached.

Run:
  .venv/bin/python mus-rs/tools/gen_threader_bank.py \
      --out <dir> --core 20000 --contrast 1200 --witness 400
"""

from __future__ import annotations

import argparse
import json
import math
import subprocess
import sys
from pathlib import Path

import numpy as np
from scipy.stats import qmc
from scipy.spatial.transform import Rotation

ROOT = Path(__file__).resolve().parents[2]
MUS = ROOT / "mus-rs/target/release/mus"
sys.path.insert(0, str(ROOT / "paper" / "ariadne-gesture-compiler" / "reference"))
from ariadne_gesture.closed_loop import compile_exact_closed_loop_so3  # noqa: E402

SR = 48000
SEED = 0x7423AD37
BODIES = ["guitar", "violin", "cello", "bass", "mandolin"]
AUTOMATABLE = ["couple", "chirality", "orbit", "orbit_depth", "curvature",
               "body", "buzz", "sus", "damp", "bow", "bow_speed", "breath"]

rpc_id = 0
service = None


def start_service():
    global service
    service = subprocess.Popen(
        [str(MUS), "service"], stdin=subprocess.PIPE, stdout=subprocess.PIPE, text=True,
    )


def call(method, params):
    global rpc_id
    rpc_id += 1
    service.stdin.write(json.dumps({"id": rpc_id, "method": method, "params": params}) + "\n")
    service.stdin.flush()
    response = json.loads(service.stdout.readline())
    if "error" in response:
        return {"__refusal__": response["error"]}
    return response["result"]


def engine_rev() -> str:
    return subprocess.run(
        ["git", "-C", str(ROOT), "rev-parse", "--short", "HEAD"],
        capture_output=True, text=True,
    ).stdout.strip()


def project_safe(theta: dict) -> dict:
    couple = theta["couple"]
    if couple > 1e-6:
        theta["orbit_depth"] = round(min(theta["orbit_depth"], 0.24 / couple), 4)
        theta["curvature"] = round(min(theta["curvature"], 0.22 / couple), 4)
    return theta


def sobol_theta(u: np.ndarray) -> dict:
    """Map one Sobol point in [0,1)^20 to a safe patch."""
    theta = {
        "synth": "weave",
        "sus": round(float(0.5 * (10.0 / 0.5) ** u[0]), 3),
        "damp": round(float(0.05 + 0.55 * u[1]), 3),
        "pick": round(float(0.2 + 0.75 * u[2]), 3),
        "pos": round(float(0.06 + 0.34 * u[3]), 3),
        "body": round(float(u[4]), 3),
        "body_size": round(float(0.8 + 0.5 * u[5]), 3),
        "bodyp": BODIES[int(u[6] * len(BODIES)) % len(BODIES)],
        "stiff": round(float(0.75 * u[7]), 3),
        "couple": round(float(0.30 * u[8]), 4),
        "chirality": round(float(-1.0 + 2.0 * u[9]), 3),
        "orbit": round(float(8.0 * u[10] ** 2), 3),
        "orbit_depth": round(float(u[11]), 3),
        "curvature": round(float(u[12]), 3),
        "courses": int(5 + u[13] * 12),
        "dimension": round(float(0.55 + 2.45 * u[14]), 3),
        "bow": round(float(max(0.0, u[15] * 1.4 - 0.4)), 3),
        "bow_speed": round(float(0.2 + 0.6 * u[16]), 3),
        "breath": round(float(max(0.0, u[17] * 1.4 - 0.4)), 3),
        "buzz": round(float(0.35 * u[18]), 3),
        "detune": round(float(25.0 * u[19] ** 2), 2),
    }
    return project_safe(theta)


def sobol_gamma(rng: np.random.Generator) -> dict:
    n_notes = int(rng.choice([1, 1, 2, 3]))
    root = int(rng.integers(28, 84))
    intervals = rng.choice([3, 4, 5, 7, 12], size=max(0, n_notes - 1))
    midis = [root] + [int(root + int(np.sum(intervals[: i + 1]))) for i in range(n_notes - 1)]
    midis = [min(m, 96) for m in midis]
    slot = float(np.exp(rng.uniform(np.log(0.15), np.log(2.5))))
    gliss = 1.0
    if rng.random() < 0.5:
        gliss = float(2.0 ** rng.uniform(-2.0, 2.0))
    trajectory = []
    n_frames = int(rng.choice([0, 0, 1, 2, 3, 4]))
    if n_frames:
        keys = rng.choice(AUTOMATABLE, size=min(n_frames, 3), replace=False)
        times = np.sort(rng.uniform(0.05, slot * 0.9, size=n_frames))
        for t in times:
            key = str(rng.choice(keys))
            value = {"couple": rng.uniform(0, 0.3), "chirality": rng.uniform(-1, 1),
                     "orbit": rng.uniform(0, 8), "orbit_depth": rng.uniform(0, 0.8),
                     "curvature": rng.uniform(0, 0.7), "body": rng.uniform(0, 1),
                     "buzz": rng.uniform(0, 0.35), "sus": rng.uniform(0.5, 8),
                     "damp": rng.uniform(0.05, 0.6), "bow": rng.uniform(0, 1),
                     "bow_speed": rng.uniform(0.2, 0.8), "breath": rng.uniform(0, 1),
                     }[key]
            trajectory.append({"atSeconds": round(float(t), 3),
                               "set": {key: round(float(value), 4)}})
    return {"midis": midis, "slotSeconds": round(slot, 3),
            "glissRatio": round(gliss, 4), "trajectory": trajectory}


def witness_words(rng: np.random.Generator):
    angle = float(rng.uniform(0.3, 2.6))
    axis = rng.standard_normal(3)
    axis /= np.linalg.norm(axis)
    target = Rotation.from_rotvec(axis * angle).as_matrix()
    cert = compile_exact_closed_loop_so3(target)
    forward = [(g.i, g.j, g.theta) for g in cert.schedule]
    inverse = forward + [(i, j, -t) for (i, j, t) in reversed(forward)]
    def frames(gates, start, span):
        times = np.linspace(start, start + span, len(gates))
        return [{"atSeconds": round(float(t), 4), "courses": [int(i), int(j)],
                 "theta": round(float(th), 8)}
                for (i, j, th), t in zip(gates, times)]
    return {"angle": round(angle, 4), "axis": [round(float(a), 4) for a in axis],
            "null": [], "word": frames(forward, 0.15, 1.2),
            "inverse": frames(inverse, 0.15, 1.6)}


def render_row(out, manifest, seen, row_id, stratum, group, request):
    if row_id in seen:
        return False
    result = call("renderWeaveProbe", request)
    row = {"id": row_id, "stratum": stratum, "group": group, "request": request}
    if "__refusal__" in result:
        row["refusal"] = result["__refusal__"]
    else:
        pcm = np.fromfile(result["pcm"]["path"], dtype=np.float32)
        import soundfile as sf
        sf.write(out / "audio" / f"{row_id}.wav", pcm, SR, subtype="FLOAT")
        row["receipt"] = {k: v for k, v in result.items() if k not in ("pcm", "trace")}
        row["samples"] = len(pcm)
        row["peak"] = round(float(np.abs(pcm).max()), 6)
        row["rms"] = round(float(np.sqrt((pcm.astype(np.float64) ** 2).mean())), 8)
    manifest.write(json.dumps(row) + "\n")
    manifest.flush()
    seen.add(row_id)
    return True


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, default=ROOT / "threader-bank-v0")
    parser.add_argument("--core", type=int, default=20000)
    parser.add_argument("--contrast", type=int, default=1200)
    parser.add_argument("--witness", type=int, default=400)
    args = parser.parse_args()
    out = args.out
    (out / "audio").mkdir(parents=True, exist_ok=True)

    manifest_path = out / "manifest.jsonl"
    seen: set[str] = set()
    if manifest_path.exists():
        for line in manifest_path.open():
            try:
                seen.add(json.loads(line)["id"])
            except (json.JSONDecodeError, KeyError):
                pass
    manifest = manifest_path.open("a")
    if not seen:
        manifest.write(json.dumps({
            "id": "__header__", "schema": "threader-bank/0",
            "engine": engine_rev(), "seed": SEED,
            "safe_region": "PARAMETERS.md §8 projected",
            "note": "aigua-contour stratum absent: pitch-ratio automation not yet in engine",
        }) + "\n")
        manifest.flush()

    start_service()
    rng = np.random.default_rng(SEED)
    sob = qmc.Sobol(d=20, seed=SEED)
    done = 0

    # ---- core ------------------------------------------------------------
    for k in range(args.core):
        u = sob.random(1)[0]
        theta = sobol_theta(u)
        gamma = sobol_gamma(rng)
        request = {"params": theta, **gamma}
        done += render_row(out, manifest, seen, f"core-{k:06d}", "core", None, request)
        if k % 500 == 0:
            print(f"core {k}/{args.core} (written {done})", flush=True)

    # ---- contrast --------------------------------------------------------
    for g in range(args.contrast):
        u = sob.random(1)[0]
        base_theta = sobol_theta(u)
        gamma = sobol_gamma(rng)
        kind = ["bodyp", "chirality", "order", "guitar-limit"][g % 4]
        group = f"contrast-{kind}-{g:05d}"
        variants = []
        if kind == "bodyp":
            other = rng.choice([b for b in BODIES if b != base_theta["bodyp"]])
            variants = [("a", base_theta), ("b", {**base_theta, "bodyp": str(other)})]
        elif kind == "chirality":
            variants = [("a", base_theta),
                        ("b", {**base_theta, "chirality": -base_theta["chirality"]})]
        elif kind == "order":
            up = [{"atSeconds": 0.2, "set": {"couple": 0.28}},
                  {"atSeconds": 0.6, "set": {"chirality": 0.8}},
                  {"atSeconds": 1.0, "set": {"couple": base_theta["couple"]}},
                  {"atSeconds": 1.4, "set": {"chirality": base_theta["chirality"]}}]
            swapped = [up[1] | {"atSeconds": 0.2}, up[0] | {"atSeconds": 0.6},
                       up[3] | {"atSeconds": 1.0}, up[2] | {"atSeconds": 1.4}]
            long_gamma = {**gamma, "slotSeconds": max(gamma["slotSeconds"], 1.8)}
            for tag, frames in (("ab", up), ("ba", swapped)):
                request = {"params": base_theta, **long_gamma, "trajectory": frames}
                done += render_row(out, manifest, seen, f"{group}-{tag}", "contrast",
                                   group, request)
            continue
        else:
            variants = [("a", {**base_theta, "couple": 0.0, "orbit": 0.0}),
                        ("b", {**base_theta, "couple": max(base_theta["couple"], 0.1)})]
        for tag, theta in variants:
            request = {"params": theta, **gamma}
            done += render_row(out, manifest, seen, f"{group}-{tag}", "contrast",
                               group, request)
        if g % 100 == 0:
            print(f"contrast {g}/{args.contrast} (written {done})", flush=True)

    # ---- witness ---------------------------------------------------------
    for g in range(args.witness):
        u = sob.random(1)[0]
        theta = sobol_theta(u)
        theta["courses"] = max(theta["courses"], 5)
        root = int(rng.integers(40, 70))
        gamma = {"midis": [root, root + 7, root + 12], "slotSeconds": 2.4,
                 "glissRatio": 1.0, "trajectory": []}
        words = witness_words(rng)
        group = f"witness-{g:05d}"
        for tag in ("null", "word", "inverse"):
            request = {"params": theta, **gamma, "gesture": words[tag]}
            done += render_row(out, manifest, seen, f"{group}-{tag}", "witness",
                               group, request)
        meta_row = {"id": f"{group}-meta", "stratum": "witness-meta", "group": group,
                    "angle": words["angle"], "axis": words["axis"]}
        if f"{group}-meta" not in seen:
            manifest.write(json.dumps(meta_row) + "\n")
            manifest.flush()
            seen.add(f"{group}-meta")
        if g % 50 == 0:
            print(f"witness {g}/{args.witness} (written {done})", flush=True)

    manifest.close()
    print(f"DONE: {done} new renders, manifest {manifest_path}")
    service.stdin.close()


if __name__ == "__main__":
    main()
