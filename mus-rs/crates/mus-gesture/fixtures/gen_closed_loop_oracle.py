"""Emit the Rust replay fixture for the exact closed-control SO(3) compiler.

`paper/ariadne-gesture-compiler/reference/results.json` carries the closed-loop
experiment only as aggregates (worst endpoint error, factor-count mismatches),
so it cannot drive a cross-implementation replay of the *word*.  The Phase 2
spec is explicit that this fixture must be generated fresh from the oracle
rather than parsed out of that committed receipt.  This script calls
`ariadne_gesture.closed_loop.compile_exact_closed_loop_so3` — the same float64
oracle the paper reports — and dumps, per case, everything `mus-gesture` needs
to recompute the identical twelve-gate word in Rust:

    authored graph -> spanning tree -> leaf order -> SO(3) target
        -> (principal angle, axis) -> balanced generator angle
        -> conjugator and the branch that built it
        -> twelve-gate closed word -> per-edge closure -> timing

The conjugator, its branch, and the local commutator axis are not fields of
`ExactClosedLoopCertificate`, so they are recomputed here through the oracle's
own `_rotation_vector` / `_rotation_from_to` helpers — the same code the
compiler ran, not a reimplementation.  The branch label mirrors the branch test
inside `_rotation_from_to` (`|n0 x n| < 1e-12`, then the sign of `n0 . n`).

The oracle's own `ExactClosedLoopCertificate.thermodynamic_length` is a
*unit-friction* length, so it is recorded separately as
`unit_thermodynamic_length`.  The friction-weighted timing that `mus-gesture`
produces is generated by calling the oracle's `thermodynamic_schedule` on the
closed word with the same authored friction, exactly as the Phase 1 fixture
does.

Usage (from anywhere; paths are resolved relative to this file):

    <repo>/.venv/bin/python \
        mus-rs/crates/mus-gesture/fixtures/gen_closed_loop_oracle.py

Writes `closed_loop_oracle.json` next to this script.
"""

from __future__ import annotations

from pathlib import Path
import json
import math
import sys

import numpy as np

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[3]
REFERENCE = REPO / "paper" / "ariadne-gesture-compiler" / "reference"
sys.path.insert(0, str(REFERENCE))

from ariadne_gesture import (  # noqa: E402
    Graph,
    balanced_commutator_angle,
    canonical_edge,
    compile_exact_closed_loop_so3,
    compile_so_on_tree,
    givens,
    random_so,
    thermodynamic_schedule,
)
from ariadne_gesture.closed_loop import (  # noqa: E402
    _rotation_from_to,
    _rotation_vector,
)

SEED = 0xC105ED10
SCHEMA = "mus-gesture/closed-loop-oracle/1"
DURATION = 2.0
RANDOM_TARGETS = 96
ANTIPODAL_SINE_THRESHOLD = 1.0e-12

GRAPHS = {
    "path_012": Graph(n=3, edges=(canonical_edge(0, 1), canonical_edge(1, 2))),
    "path_021": Graph(n=3, edges=(canonical_edge(0, 2), canonical_edge(1, 2))),
    "triangle": Graph(
        n=3,
        edges=(canonical_edge(0, 1), canonical_edge(0, 2), canonical_edge(1, 2)),
    ),
}


def rodrigues(axis, angle: float):
    """A rotation of `angle` about `axis`, written out independently."""
    axis = np.asarray(axis, dtype=np.float64)
    axis = axis / np.linalg.norm(axis)
    generator = np.array(
        [
            [0.0, -axis[2], axis[1]],
            [axis[2], 0.0, -axis[0]],
            [-axis[1], axis[0], 0.0],
        ],
        dtype=np.float64,
    )
    return (
        np.eye(3, dtype=np.float64)
        + math.sin(angle) * generator
        + (1.0 - math.cos(angle)) * (generator @ generator)
    )


def local_commutator_axis(target_angle: float):
    """The axis of C0(t) for the balanced generator angle of `target_angle`."""
    t = balanced_commutator_angle(target_angle)
    a0 = givens(3, 0, 1, t)
    b0 = givens(3, 1, 2, t)
    local = a0 @ b0 @ a0.T @ b0.T
    rotvec = _rotation_vector(local)
    return rotvec / np.linalg.norm(rotvec)


def conjugator_branch(source, target) -> str:
    """The branch `_rotation_from_to` takes, by its own test."""
    sine = float(np.linalg.norm(np.cross(source, target)))
    if sine < ANTIPODAL_SINE_THRESHOLD:
        return "aligned" if float(np.dot(source, target)) > 0.0 else "antipodal"
    return "general"


def case(name: str, graph_name: str, target, rng) -> dict:
    graph = GRAPHS[graph_name]
    certificate = compile_exact_closed_loop_so3(
        target, graph=graph, duration=DURATION
    )
    friction = {
        edge: float(math.exp(rng.uniform(-1.2, 1.2))) for edge in graph.edges
    }
    thermo = thermodynamic_schedule(
        certificate.schedule, edge_friction=friction, duration=DURATION
    )

    rotvec = _rotation_vector(np.asarray(target, dtype=np.float64))
    angle = float(np.linalg.norm(rotvec))
    if angle > 0.0:
        axis = rotvec / angle
        local_axis = local_commutator_axis(angle)
        conjugator = _rotation_from_to(local_axis, axis)
        branch = conjugator_branch(local_axis, axis)
    else:
        axis = np.zeros(3, dtype=np.float64)
        local_axis = np.zeros(3, dtype=np.float64)
        conjugator = np.eye(3, dtype=np.float64)
        branch = "aligned"

    # The tree and peel this graph resolves to under the deterministic plan;
    # both macros are compiled on it, so one probe compile suffices.
    plan = compile_so_on_tree(np.eye(3), graph)

    expected_gates = 0 if angle < 1e-14 else 12
    assert certificate.factor_count == expected_gates, (
        f"{name}: {certificate.factor_count} gates, expected {expected_gates}"
    )
    assert all(gate.edge in set(graph.edges) for gate in certificate.schedule)

    return {
        "name": name,
        "graph": graph_name,
        "graph_edges": [list(edge) for edge in graph.edges],
        "edge_friction": [
            [edge[0], edge[1], friction[edge]] for edge in graph.edges
        ],
        "tree_edges": [list(edge) for edge in plan.tree_edges],
        "leaf_order": list(plan.leaf_order),
        "target": [[float(value) for value in row] for row in target],
        "target_angle_rad": angle,
        "target_axis": [float(value) for value in axis],
        "balanced_generator_angle_rad": certificate.balanced_generator_angle_rad,
        "local_commutator_axis": [float(value) for value in local_axis],
        "conjugator": [[float(value) for value in row] for row in conjugator],
        "conjugator_branch": branch,
        "factor_count": certificate.factor_count,
        "schedule": [
            {"i": gate.i, "j": gate.j, "theta": gate.theta}
            for gate in certificate.schedule
        ],
        "reconstruction_error_fro": certificate.reconstruction_error_fro,
        "reconstruction_error_rad": certificate.reconstruction_error_rad,
        "orthogonality_error_fro": certificate.orthogonality_error_fro,
        "max_edge_control_closure": certificate.max_edge_control_closure,
        "duration": DURATION,
        "unit_thermodynamic_length": certificate.thermodynamic_length,
        "thermodynamic_length": thermo.thermodynamic_length,
        "minimum_quadratic_cost": thermo.minimum_quadratic_cost,
        "segment_durations": list(thermo.segment_durations),
        "constant_speed_residual": thermo.constant_speed_residual,
    }


def main() -> None:
    rng = np.random.default_rng(SEED)
    graph_names = list(GRAPHS)
    cases: list[dict] = []

    # The three named angles the packet reports (37, 103, 171 degrees).
    named_axis = np.array([1.0, -2.0, 3.0], dtype=np.float64)
    for degrees in (37.0, 103.0, 171.0):
        cases.append(
            case(
                f"named-{int(degrees):03d}deg",
                "path_012",
                rodrigues(named_axis, math.radians(degrees)),
                rng,
            )
        )

    # Haar targets, cycling the three connected three-mode graphs.
    for index in range(RANDOM_TARGETS):
        graph_name = graph_names[index % len(graph_names)]
        cases.append(
            case(f"haar-{index:03d}-{graph_name}", graph_name, random_so(3, rng), rng)
        )

    # The identity: the empty word.
    cases.append(case("identity", "path_012", np.eye(3), rng))

    # Near-identity and near-pi corpora, on every graph.
    hard_axis = np.array([0.37, -0.82, 0.44], dtype=np.float64)
    hard_angles = [
        ("near-identity-1e-13", 1.0e-13),
        ("near-identity-1e-9", 1.0e-9),
        ("near-identity-1e-6", 1.0e-6),
        ("near-pi-1e-6", math.pi - 1.0e-6),
        ("near-pi-1e-9", math.pi - 1.0e-9),
        ("near-pi-1e-13", math.pi - 1.0e-13),
        ("exact-pi", math.pi),
    ]
    for label, angle in hard_angles:
        for graph_name in graph_names:
            cases.append(
                case(
                    f"{label}-{graph_name}",
                    graph_name,
                    rodrigues(hard_axis, angle),
                    rng,
                )
            )

    # The two degenerate conjugator branches, aimed exactly at the local
    # commutator axis and at its negation.
    for phi in (0.4, 1.234, 2.9):
        local_axis = local_commutator_axis(phi)
        cases.append(
            case(
                f"aligned-branch-phi{phi}",
                "path_012",
                rodrigues(local_axis, phi),
                rng,
            )
        )
        cases.append(
            case(
                f"antipodal-branch-phi{phi}",
                "path_012",
                rodrigues(-local_axis, phi),
                rng,
            )
        )

    branches = sorted({entry["conjugator_branch"] for entry in cases})
    assert branches == ["aligned", "antipodal", "general"], branches

    payload = {
        "schema": SCHEMA,
        "seed": SEED,
        "oracle": "paper/ariadne-gesture-compiler/reference/ariadne_gesture",
        "oracle_entry": "closed_loop.compile_exact_closed_loop_so3",
        "numpy": np.__version__,
        "duration": DURATION,
        "case_count": len(cases),
        "cases": cases,
    }
    out = HERE / "closed_loop_oracle.json"
    out.write_text(json.dumps(payload, indent=1, sort_keys=True) + "\n")
    print(f"wrote {out} ({out.stat().st_size} bytes, {len(cases)} cases)")


if __name__ == "__main__":
    main()
